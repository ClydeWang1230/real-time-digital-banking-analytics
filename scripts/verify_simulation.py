"""Verify deterministic generation and file replay with isolated live Kafka data."""

import argparse
from dataclasses import asdict, replace
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
from uuid import uuid4

import duckdb
from confluent_kafka.admin import AdminClient, NewTopic

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config import PROJECT_ROOT, Settings, load_settings
from producer.batch import load_batch, prepare_batch
from producer.event_generator import SimulationSpec
from producer.producer import publish_records
from scripts.verify_ingestion import committed_offset, require, run_batch


def run_counts(path: Path) -> list[dict]:
    with duckdb.connect(str(path), read_only=True) as connection:
        rows = connection.execute("""
            SELECT payload->>'run_id', COUNT(*), COUNT(DISTINCT event_id),
                   COUNT(DISTINCT customer_id), COUNT(DISTINCT session_id)
            FROM raw_events GROUP BY 1 ORDER BY 1
        """).fetchall()
        require(connection.execute("SELECT COUNT(*) FROM rejected_events").fetchone()[0] == 0,
                "Generated or replayed events were rejected")
        return [dict(zip(("run_id", "events", "unique_event_ids", "customers", "sessions"), row))
                for row in rows]


def verify(bootstrap: str) -> Path:
    suffix = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid4().hex[:8]
    output = PROJECT_ROOT / "artifacts" / "verification" / ("p03-" + suffix)
    output.mkdir(parents=True, exist_ok=False)
    topic = "banking-p03-" + suffix.lower()
    settings = replace(Settings(), kafka_bootstrap_servers=bootstrap, kafka_topic=topic,
                       kafka_group_id=topic + "-consumer", db_path=output / "simulation.duckdb")
    report_path = output / "report.json"
    report = {"status": "running", "topic": topic, "group": settings.kafka_group_id,
              "database": str(settings.db_path)}
    try:
        first_spec = SimulationSpec.create(100, seed=42, base_time="2026-11-08T00:00:00Z")
        first = prepare_batch(first_spec, output / "batches")
        regenerated = prepare_batch(first_spec, output / "regenerated")
        for name in ("manifest.json", "events.jsonl"):
            require((first.directory / name).read_bytes() == (regenerated.directory / name).read_bytes(),
                    f"Regenerated {name} bytes differ")
        second = prepare_batch(SimulationSpec.create(100, seed=7, base_time="2026-11-08T02:00:00Z"),
                               output / "batches")
        report["batches"] = [first.manifest, second.manifest]
        report["regeneration_bytes_equal"] = True
        print(f"Prepared two batches; regenerated bytes match. Creating isolated topic: {topic}", flush=True)
        admin = AdminClient({"bootstrap.servers": bootstrap})
        admin.create_topics([NewTopic(topic, num_partitions=1, replication_factor=1)],
                            request_timeout=15)[topic].result(timeout=20)
        total = 0
        report["phases"] = []
        for name, batch, expected_outcome in (("first_batch", first, "inserted"),
                                               ("file_replay", load_batch(first.directory), "duplicate"),
                                               ("second_batch", second, "inserted")):
            count = batch.manifest["event_count"]
            print(f"Publishing {name}: {count} saved messages...", flush=True)
            delivery = publish_records(batch.messages, settings)
            require(delivery.acknowledged == count, "Broker acknowledgements did not reconcile")
            consumption = run_batch(settings, count)
            require(getattr(consumption, expected_outcome) == count and consumption.committed == count,
                    f"Unexpected result for {name}: {asdict(consumption)}")
            total += count
            require(committed_offset(settings) == total, "Kafka group progress did not reconcile")
            snapshot = run_counts(settings.db_path)
            report["phases"].append({"name": name, "producer": asdict(delivery),
                                    "consumer": asdict(consumption), "runs": snapshot})
        require(report["phases"][0]["runs"] == report["phases"][1]["runs"],
                "File replay changed stored event/customer/session counts")
        expected = sorted([{"run_id": b.manifest["simulation"]["run_id"],
                            "events": b.manifest["event_count"],
                            "unique_event_ids": b.manifest["event_count"],
                            "customers": 100, "sessions": 100} for b in (first, second)],
                          key=lambda row: row["run_id"])
        require(report["phases"][-1]["runs"] == expected, "Per-run database counts did not reconcile")
        with duckdb.connect(str(settings.db_path), read_only=True) as connection:
            totals = connection.execute("""
                SELECT COUNT(*), COUNT(DISTINCT event_id), COUNT(DISTINCT customer_id),
                       COUNT(DISTINCT session_id) FROM raw_events
            """).fetchone()
            unique = first.manifest["event_count"] + second.manifest["event_count"]
            require(totals == (unique, unique, 200, 200), "Batch identities overlap")
            require(connection.execute("SELECT COUNT(*) FROM processed_messages").fetchone()[0] == total,
                    "Source ledger count mismatch")
        report["status"] = "passed"
    except Exception as exc:
        report["status"] = "failed"
        report["error"] = f"{type(exc).__name__}: {exc}"
        raise
    finally:
        report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(f"Verification report: {report_path}", flush=True)
    print("PASS: deterministic regeneration, saved-file replay, and two distinct batches.", flush=True)
    return report_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bootstrap", help="Defaults to the shared Kafka bootstrap setting")
    arguments = parser.parse_args()
    verify(arguments.bootstrap or load_settings().kafka_bootstrap_servers)
